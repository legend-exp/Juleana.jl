# Generates `src/tui_logo.jl`, the logo as character art for the terminal user interface,
# from `logo/logo.png`. Run by hand after the logo changes:
#
#     julia logo/terminal_logo.jl
#
# The script uses a temporary environment, so the package gets no dependency on the image
# packages.

using Pkg
Pkg.activate(; temp = true)
Pkg.add(["PNGFiles", "ColorTypes"])

using PNGFiles: PNGFiles
using ColorTypes: ColorTypes

const ROOT = dirname(@__DIR__)

# Palette characters: background, outline, and the three colors of the logo.
const PALETTE = (' ' => (255, 255, 255), 'k' => (0, 0, 0), 'r' => (0xcb, 0x3c, 0x33),
    'g' => (0x38, 0x98, 0x26), 'p' => (0x95, 0x58, 0xb2))

# Palette character of a pixel with 8-bit channels `r`, `g`, `b` and alpha `a`.
function classify(r, g, b, a)
    a < 128 && return ' '
    # blend onto white, so that transparent and white backgrounds agree
    r, g, b = ((c * a + 255 * (255 - a)) / 255 for c in (r, g, b))
    best = ' '
    best_distance = Inf
    for (char, (pr, pg, pb)) in PALETTE
        d = (r - pr)^2 + (g - pg)^2 + (b - pb)^2
        d < best_distance && ((best, best_distance) = (char, d))
    end
    return best
end

# Pixel region of the image that holds the lettering: right of the first circle and below the
# top of its tallest letters, with the line that leaves the second circle above the lowercase
# letters left out.
lettering(row, col) = (col >= 195 && row >= 242 && col < 480) || (col >= 480 && row >= 280)

# Scale the character map `chars` (rows of palette characters) to `width` x `height` pixels.
# A pixel takes the most frequent non-background character of its block if the non-background
# part of the block is at least `coverage`, so that thin outlines survive. Blocks that lie
# mostly in the lettering need `text_coverage`, so that the gaps between the letters stay open.
# Otherwise the pixel is background.
function downsample(chars, width, height; coverage, text_coverage)
    nrows, ncols = size(chars)
    rows = String[]
    for j in 1:height
        r1, r2 = round(Int, (j - 1) * nrows / height) + 1, round(Int, j * nrows / height)
        line = Char[]
        for i in 1:width
            c1, c2 = round(Int, (i - 1) * ncols / width) + 1, round(Int, i * ncols / width)
            block = view(chars, r1:r2, c1:c2)
            counts = Dict(c => count(==(c), block) for c in "kgpr")
            total = sum(values(counts))
            winner = argmax(counts)
            in_text = count(rc -> lettering(rc[1], rc[2]), CartesianIndices((r1:r2, c1:c2))) > length(block) / 2
            push!(line, total >= (in_text ? text_coverage : coverage) * length(block) ? winner : ' ')
        end
        push!(rows, String(line))
    end
    return rows
end

img = PNGFiles.load(joinpath(ROOT, "logo", "logo.png"))
chars = map(img) do px
    u8(x) = round(Int, 255 * x)
    classify(u8(ColorTypes.red(px)), u8(ColorTypes.green(px)), u8(ColorTypes.blue(px)), u8(ColorTypes.alpha(px)))
end

# The two circles without the lettering and the line from the second circle to the right.
mark = copy(chars)
mark[250:end, 196:end] .= ' '
mark[:, 399:end] .= ' '
mark = mark[1:345, 1:398]

# `(name, characters, width in cells, height in pixel rows, coverage, text coverage)`; two pixel
# rows make a cell row
const SIZES = (
    (:large, chars, 64, 32, 0.15, 0.4),
    (:medium, chars, 48, 24, 0.15, 0.45),
    (:mark, mark, 32, 28, 0.12, 0.12),
    (:mark_small, mark, 24, 20, 0.12, 0.12),
)

# The mark for the three cell rows of the tab bar. Downsampling cannot resolve the
# outlines and the three colored dots of a circle in six pixel rows, so this art is drawn by hand
# with `.` for the background.
const CORNER = replace.([
    "......kk.",
    ".....krgk",
    ".kk..kp.k",
    "kgpkkkkk.",
    "kr.k.....",
    ".kk......",
], '.' => ' ')

open(joinpath(ROOT, "src", "tui_logo.jl"), "w") do io
    println(io, "# This file is generated by `logo/terminal_logo.jl` from `logo/logo.png`; do not edit it by hand.")
    println(io)
    println(io, "# Logo as rows of palette characters, one character per half-block pixel: ' ' background,")
    println(io, "# 'k' outline, 'r' red, 'g' green, 'p' purple. Two pixel rows make one terminal row.")
    println(io, "const LOGO_ART = Dict{Symbol,Vector{String}}(")
    for (name, map, width, height, coverage, text_coverage) in SIZES
        println(io, "    :$name => [")
        for row in downsample(map, width, height; coverage, text_coverage)
            println(io, "        ", repr(row), ",")
        end
        println(io, "    ],")
    end
    println(io, "    :corner => [")
    for row in CORNER
        println(io, "        ", repr(row), ",")
    end
    println(io, "    ],")
    println(io, ")")
end
